-- 이미 저장된 글 요약에 남아 있는 [[번호|글자]]를 글자만 남기게 정리해요 (요약 생성 규칙 수정에 맞춤, LK-02)
-- 요약이 100자에서 잘리면서 링크 중간에 끊긴 경우(예: "[[19|클린 코드를 읽…")는 앞부분 "[[19|"만 지워요
UPDATE posts
   SET summary = regexp_replace(
                   regexp_replace(summary, '\[\[[0-9]{1,18}\|([^]\n]{1,100})\]\]', '\1', 'g'),
                   '\[\[[0-9]{1,18}\|', '', 'g')
 WHERE summary LIKE '%[[%';
